#!/bin/bash
# Switch-off must be byte-identical to stock: run off-identical.pl against
# a worktree of stock Sympa 6.2.78 and one of dkim2-wrap, over the charset
# corpus samples plus the review inputs, and compare.
# usage: off-identical.sh [SCRATCH_DIR]   (worktrees go there, then removed)
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
INTEROP=$(cd "$HERE/../.." && pwd)
SYMPA=${SYMPA:-$HOME/src/sympa}
DEPS=${SYMPA_DEPS:-$HOME/src/sympa-dev-deps/lib/perl5}
SCRATCH=${1:-$(mktemp -d)}
mkdir -p "$SCRATCH"
# The deps only; each side puts its own src/lib on @INC.
export PERL5LIB=$DEPS

cleanup() {
  for t in up wrap; do
    git -C "$SYMPA" worktree remove --force "$SCRATCH/$t" 2>/dev/null || true
  done
}
trap cleanup EXIT

for t in up wrap; do
  case $t in up) ref=6.2.78 ;; wrap) ref=dkim2-wrap ;; esac
  git -C "$SYMPA" worktree remove --force "$SCRATCH/$t" 2>/dev/null || true
  git -C "$SYMPA" worktree add -q --detach "$SCRATCH/$t" "$ref"
  # Generated by configure and gitignored; the same for both builds.
  cp "$SYMPA/src/lib/Sympa/Constants.pm" "$SCRATCH/$t/src/lib/Sympa/"
  perl "$HERE/off-identical.pl" "$SCRATCH/$t/src/lib" \
    "$INTEROP"/corpus/sample/*.eml > "$SCRATCH/$t.out"
done

total=$(wc -l < "$SCRATCH/up.out" | tr -d ' ')
same=$(paste "$SCRATCH/up.out" "$SCRATCH/wrap.out" \
  | awk -F'\t' '$1==$4 && $2==$5 && $3==$6' | wc -l | tr -d ' ')
if ! diff "$SCRATCH/up.out" "$SCRATCH/wrap.out"; then
  echo "identical: $same/$total"
  exit 1
fi
echo "identical: $same/$total"
